-- find, match, gmatch, and gsub (ADR 0034). Output must match Lua 5.4.9.
local function show(...)
  local out = {}
  for i = 1, select('#', ...) do
    local v = select(i, ...)
    -- `%q` keeps bytes past 127 as they are; write them as escapes.
    out[#out + 1] = type(v) == "string"
        and (string.gsub(string.format("%q", v), "[\128-\255]", function(c) return "\\" .. c:byte() end))
      or tostring(v)
  end
  print(table.concat(out, " "))
end
local function all(iterator)
  local out = {}
  for a, b in iterator do out[#out + 1] = tostring(a) .. (b ~= nil and "=" .. tostring(b) or "") end
  return table.concat(out, ",")
end
